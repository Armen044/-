def row(code, x0, y0, x1, y1, step):
    n = max(1, int(round(math.hypot(x1 - x0, y1 - y0) / step)))
    return [(code, x0 + (x1 - x0) * i / n, y0 + (y1 - y0) * i / n) for i in range(n + 1)]


def arc(code, c, r, a0, a1, step):
    n = max(1, int(round(math.radians(abs(a1 - a0)) * r / step)))
    return [(code, c[0] + r * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
             c[1] + r * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]



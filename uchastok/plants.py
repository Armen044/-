def check():
    beds = G.LEFT_BED.union(G.RIGHT_BED)
    bad = 0
    for c, x, y in P:
        p = Point(x, y)
        r = CAT[c][2] / 2
        if not beds.buffer(0.02).contains(p):
            print("вне посадки:", c, x, y); bad += 1
        for nm, g in (("дорожка", G.PATH), ("газон", G.LAWN), ("костровая", G.FIRE)):
            d = g.distance(p)
            if d < r * 0.55 and c not in (21,):
                print(f"{c} ({x:.2f},{y:.2f}) налезает на {nm}: {d:.2f} < {r*0.55:.2f}"); bad += 1
    fire = Point(G.FIRE_C)
    for c, x, y in P:
        d = fire.distance(Point(x, y))
        if c in (14, 7, 17, 4, 16) and d < 3.0:
            print("горючее близко к чаше:", c, round(d, 2)); bad += 1
    return bad



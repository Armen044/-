#!/usr/bin/env python3
"""Расход ЛДСП 16 по декорам: тёмный — древесный (пеналы, ниша бойлера, верхние шкафы: корпус + фасады),
светлый — однотонный (нижние шкафы: корпус + фасады + цоколь)."""
import math

T = 16
SHEET = 2.8 * 2.07                     # лист ЛДСП 2800 × 2070
WASTE = 1.15

light, dark = [], []


def add(lst, name, a, b, q=1):
    lst.append((name, a, b, q))


# ---- светлый: нижние корпуса (высота 780, глубина 580)
for w in (600, 600, 600, 500):                     # распашной, ящики, мойка, распашной (ПММ без корпуса)
    add(light, f"низ {w}: боковины", 780, 580, 2)
    add(light, f"низ {w}: дно", w - 2 * T, 580)
    add(light, f"низ {w}: царги", w - 2 * T, 100, 2)
for w in (600, 600, 500):                          # полки в распашных
    pass
add(light, "низ: полки (распашной 600, мойка, 500)", 568, 520, 1)
add(light, "", 468, 520, 1)
add(light, "угловой (500 + угол 600): боковины", 780, 580, 2)
add(light, "угловой: дно", 1100 - 2 * T, 580)
add(light, "угловой: царги", 1100 - 2 * T, 100, 2)
add(light, "цоколь низа", 3400, 100)
add(light, "фасады низа (3400 × 778)", 3400, 778)
# ---- тёмный: пеналы (глубина 582), ниша бойлера, верхние
add(dark, "ниша бойлера: боковины", 1830, 582, 2)
add(dark, "ниша бойлера: горизонты (дно, перегородка, крыша)", 568, 582, 3)
for name, horiz in (("пенал духовки", 6), ("пенал холодильника", 4)):
    add(dark, f"{name}: боковины", 2650, 582, 2)
    add(dark, f"{name}: горизонты", 568, 582, horiz)
add(dark, "цоколь пеналов", 1200, 100)
add(dark, "планка 30", 2650, 30)
add(dark, "фасады пеналов и ниши", 600, 1428 + 358 + 908 + 1778 + 468 + 3 * 398)
for w in (450, 450, 450, 450, 300, 300):
    add(dark, f"верх {w}: боковины", 830, 322, 2)
    add(dark, f"верх {w}: дно + крыша", w - 2 * T, 322, 2)
    add(dark, f"верх {w}: полка", w - 2 * T, 300, 1)
add(dark, "фасады верха прямые 4 × 450", 1800, 828)


def area(lst):
    return sum(a * b * q for _, a, b, q in lst) / 1e6


radius_area = 2 * (math.pi / 2 * 300) * 828 / 1e6
if __name__ == "__main__":
    for nm, lst in (("светлый", light), ("тёмный", dark)):
        s = area(lst)
        print(nm, round(s, 2), "м2 ->", round(s * WASTE / SHEET, 2), "листа")
    print("радиусные фасады", round(radius_area, 2))
